    """Invert the public integer endpoint; retain a prediction inside its bin."""
    value=float(np.sum(image[75:81,32:42])-np.sum(image[75:81,42:52]))
    if abs(value)<=np.finfo(np.float32).eps*120:return 0.,(-1e-4,1e-4)
